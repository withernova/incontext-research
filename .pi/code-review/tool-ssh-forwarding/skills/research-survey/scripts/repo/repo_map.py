#!/usr/bin/env python
"""Analyze a code repo and write shell/01_repo/repo_map.md.
Pragmatic, regex/grep-based: tree (capped), entry points, datasets/dataloaders, losses,
metrics, configs, TODO/FIXME gaps, and a paper<->module crosslink section to fill in."""
import sys as _sys, pathlib as _pl
_sys.path.insert(0, str(_pl.Path(__file__).resolve().parent.parent))
import argparse, pathlib, os, re, subprocess
from _common import project_root, ensure_layout, emit

SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", "dist", "build", ".eggs", "data", "logs", "wandb", ".mypy_cache", ".pytest_cache", "outputs", "checkpoints"}
CODE_EXT = {".py", ".js", ".ts", ".tsx", ".jsx", ".cpp", ".c", ".h", ".hpp", ".cc", ".cu", ".rs", ".go", ".java", ".sh", ".yaml", ".yml", ".toml", ".json", ".md"}
TREE_CAP = 400

def walk(root: pathlib.Path):
    files = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS and not d.startswith(".")]
        for f in fns:
            p = pathlib.Path(dp) / f
            if p.suffix.lower() in CODE_EXT or f.lower() in {"readme.md", "readme", "requirements.txt", "environment.yml", "makefile", "dockerfile"}:
                files.append(p)
    return files

def grep_re(files, pattern, max_hits=40):
    rx = re.compile(pattern, re.I)
    hits = []
    for p in files:
        try:
            for i, ln in enumerate(p.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
                if rx.search(ln):
                    hits.append(f"{p.relative_to(p.parents[-1] if False else p).as_posix()}:{i}: {ln.strip()[:140]}")
                    if len(hits) >= max_hits:
                        return hits
        except Exception:
            continue
    return hits

def safe_rel(p, repo):
    try:
        return p.relative_to(repo).as_posix()
    except ValueError:
        return str(p)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--repo", required=True)
    args = ap.parse_args()
    root = project_root(args.project)
    ensure_layout(root)
    (root / "shell" / "01_repo").mkdir(parents=True, exist_ok=True)
    repo = pathlib.Path(args.repo).resolve()
    if not repo.exists():
        sys.exit(f"[err] repo not found: {repo}")
    files = walk(repo)

    def hits(pat, n=40):
        rx = re.compile(pat, re.I)
        out = []
        for p in files:
            try:
                for i, ln in enumerate(p.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
                    if rx.search(ln):
                        out.append(f"{safe_rel(p, repo)}:{i}: {ln.strip()[:140]}")
                        if len(out) >= n:
                            return out
            except Exception:
                continue
        return out

    entry = hits(r"if __name__ == ['\"]__main__['\"]|def main\(|argparse|ArgumentParser|cli\(|app\.run|@click|typer\.run")
    datasets = hits(r"Dataset|DataLoader|build_dataloader|load_data|get_dataloader|class \w*Dataset")
    losses = hits(r"loss|criterion|nll|cross_entropy|focal|dice|iou|contrastive|triplet")
    metrics = hits(r"def .*metric|@torch\.no_grad|accuracy|precision|recall|map\b|coco_eval|evaluate\(")
    todos = hits(r"TODO|FIXME|XXX|HACK|stub|NotImplemented", n=60)
    configs = [safe_rel(p, repo) for p in files if p.suffix.lower() in {".yaml", ".yml", ".toml"} or "config" in p.name.lower()]

    tree = sorted(safe_rel(p, repo) for p in files)[:TREE_CAP]

    md = f"""# Repo Map — {repo.name}

> generated by research-survey/repo_map.py from `{repo}`
> Fill the cross-link section manually using the seed papers.

## Architecture / file tree (capped {TREE_CAP})
```
{chr(10).join(tree)}
```

## Entry points
{chr(10).join(entry) or "_none found_"}

## Datasets / dataloaders
{chr(10).join(datasets) or "_none found_"}

## Losses
{chr(10).join(losses) or "_none found_"}

## Metrics
{chr(10).join(metrics) or "_none found_"}

## Configs
{chr(10).join(configs) or "_none found_"}

## TODO / FIXME / stubs / gaps
{chr(10).join(todos) or "_none found_"}

## Paper <-> Module cross-link  (fill in)
| Seed paper [[citekey]] | Repo module(s) | What it grounds |
|---|---|---|
|  |  |  |

## Grounding anchor (3-5 facts about this repo that constrain the idea)
- (e.g. "Backbone is Swin-T, not ViT — idea must account for this")
- (e.g. "No distributed training code — experiments are single-node")

## Idea <-> repo contradictions / assumptions to check
- (flag anything the idea assumes that the repo doesn't support)
"""
    out = root / "shell" / "01_repo" / "repo_map.md"
    out.write_text(md, encoding="utf-8")
    emit({"repo": str(repo), "files_scanned": len(files), "repo_map": str(out)})

if __name__ == "__main__":
    main()