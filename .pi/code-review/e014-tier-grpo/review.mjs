import fs from 'node:fs';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const root='/home/zhengyuesong/.nvm/versions/node/v24.19.0/lib/node_modules/@earendil-works/pi-coding-agent/node_modules';
const {createJiti}=require(root+'/jiti');
const jiti=createJiti(import.meta.url,{alias:{typebox:root+'/typebox/build/index.mjs'},moduleCache:false});
const init=await jiti.import('/home/zhengyuesong/Tools/survey-tool/extensions/code-change-review/index.ts',{default:true});
